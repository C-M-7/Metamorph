CREATE TABLE conversion_logs (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    conversion_id VARCHAR(36) NOT NULL UNIQUE,
    user_id BIGINT NULL,
    input_file_id BIGINT NOT NULL,
    output_file_id BIGINT NULL,
    source_format VARCHAR(20) NOT NULL,
    target_format VARCHAR(20) NOT NULL,
    execution_strategy ENUM('IN_MEMORY', 'WORKER') NOT NULL DEFAULT 'IN_MEMORY',
    status ENUM('PENDING', 'VALIDATING', 'PROCESSING', 'COMPLETED', 'FAILED') NOT NULL DEFAULT 'PENDING',
    row_count BIGINT NULL,
    error_message TEXT NULL,
    disabled BOOLEAN NOT NULL DEFAULT FALSE,
    extras JSON NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP NULL,
    completed_at TIMESTAMP NULL,
    CONSTRAINT fk_conv_logs_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_conv_logs_input_file FOREIGN KEY (input_file_id) REFERENCES file_metadata(id) ON DELETE RESTRICT,
    CONSTRAINT fk_conv_logs_output_file FOREIGN KEY (output_file_id) REFERENCES file_metadata(id) ON DELETE SET NULL,
    INDEX idx_conv_logs_conversion_id (conversion_id),
    INDEX idx_conv_logs_user_id (user_id),
    INDEX idx_conv_logs_input_file_id (input_file_id),
    INDEX idx_conv_logs_output_file_id (output_file_id),
    INDEX idx_conv_logs_status (status)
);
